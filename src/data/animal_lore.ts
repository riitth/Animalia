/** ค้นหาหรือสร้างเนื้อหาสารานุกรมสัตว์โลกสำหรับฮีโร่ตัวใดก็ได้ใน 170 ตัว */
export function getAnimalLore(heroId: string, heroMeta: {
  name: string;
  rarity?: string;
  element?: string;
  role?: string;
  archetype?: string;
  signatureName?: string;
  ability?: { name: string; description: string };
}): AnimalLoreData {
  // 1. ถ้ามีข้อมูลเขียนไว้เฉพาะใน JSON ให้นำมาใช้ก่อนทันที
  const existing = ANIMAL_LORE_MAP.get(heroId);
  if (existing) {
    return existing;
  }

  // 2. ถ้าไม่มี ให้วิเคราะห์ชื่อสัตว์และข้อมูลฮีโร่เพื่อสร้างสารานุกรมชีววิทยาและเรื่องเล่าแฟนตาซีที่ตรงกัน
  const name = heroMeta.name || heroId;
  const element = heroMeta.element || 'fire';
  const role = heroMeta.role || 'Striker';

  // หาหมวดหมู่ชีววิทยาตามคำในชื่อสัตว์
  let categoryInfo = {
    cat: 'สัตว์ป่าพื้นถิ่นตามธรรมชาติ (Fauna)',
    diet: 'กินทั้งพืชและสัตว์ (Omnivore) ตามฤดูกาล',
    habitat: 'ผืนป่าธรรมชาติ ทุ่งหญ้า และแหล่งน้ำอันอุดมสมบูรณ์'
  };

  for (const [key, val] of Object.entries(ANIMAL_CATEGORY_DICT)) {
    if (name.includes(key)) {
      categoryInfo = val;
      break;
    }
  }

  // สร้างเรื่องเล่าแฟนตาซีตามธาตุ
  const elementalOriginFn = ELEMENT_ORIGIN_THEMES[element] || ELEMENT_ORIGIN_THEMES.fire;
  const elementalOrigin = elementalOriginFn(name, role);

  const abilityName = heroMeta.ability?.name ? `[${heroMeta.ability.name}]` : 'ความสามารถตามธรรมชาติ';
  const abilityDesc = heroMeta.ability?.description || 'เสริมความแข็งแกร่งในการต่อสู้';
  const sigName = heroMeta.signatureName ? `[${heroMeta.signatureName}]` : 'ท่าไม้ตายประจำตัว';

  return {
    scientificName: `${name.replace(/\s+/g, '')} silvestris`,
    category: categoryInfo.cat,
    naturalHabitat: categoryInfo.habitat,
    diet: categoryInfo.diet,
    physicalFeatures: `มีสรีระที่ปรับตัวเข้ากับสภาพแวดล้อมได้อย่างสมบูรณ์แบบ ทั้งประสาทสัมผัสที่ว่องไวและกล้ามเนื้อที่เหมาะกับบทบาท ${role}`,
    natureBehavior: `ดำรงชีวิตอย่างกลมกลืนกับธรรมชาติในถิ่นอาศัย มีสัญชาตญาณในการเอาตัวรอด การหาอาหาร และการปกป้องอาณาเขตอย่างชาญฉลาด`,
    elementalOrigin,
    didYouKnow: `ในธรรมชาติ ${name} มีประสาทสัมผัสและพฤติกรรมเฉพาะตัวที่น่าทึ่ง ช่วยรักษาสมดุลของระบบนิเวศในถิ่นที่อยู่อาศัยมาอย่างยาวนาน`,
    combatConnection: `พฤติกรรมเด่นในธรรมชาติได้รับการสืบทอดมาเป็น Ability ${abilityName} ซึ่งช่วย${abilityDesc} และสะท้อนออกมาเป็นท่าไม้ตายปลดปล่อยพลัง ${sigName}`
  };
}

